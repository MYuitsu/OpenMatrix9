fn fixture(c:&FeatureContract)->Request {
    let mut r=Request { document_revision:Some(1), ..Request::default() };
    for role in c.roles {
        for i in 0..role.min {
            r.inputs.push(Input { role:role.name.into(),kind:role.kind,key:format!("{}-{i}",role.name),
                point:if role.kind==InputKind::Point {Some([i as f64,0.,0.])} else {None} });
        }
    }
    for p in c.parameters {
        if !p.required {continue;}
        let v=match p.kind {ParameterKind::Number=>Value::Number(1.),ParameterKind::Boolean=>Value::Boolean(false),
            ParameterKind::Choice=>Value::Choice("fixture".into()),ParameterKind::Text=>Value::Text(String::new()),
            ParameterKind::Reference=>Value::Reference("fixture".into())};
        r.options.insert(p.name.into(),v);
    }
    r
}
