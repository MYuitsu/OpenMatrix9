//! The package files are generated from the menu crates and checked here:
//!
//! - `addon/om9_addon.toml`: every menu crate's `[[commands]]` and `[[settings]]` (settings
//!   scoped to their commands);
//! - `addon/commands/<Menu>/<Code>.md`: one page per command (menu position, icon, names,
//!   how to use it, options);
//! - `addon/README.md`: the index.
//!
//! Regenerate with `OM9_UPDATE_PACKAGE=1 cargo test -p om9-addon-matrix --test package`.
use om9_addons::toml::{self, Table, Value};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn s<'a>(t: &'a Table, k: &str) -> Option<&'a str> {
    t.get(k).and_then(Value::as_str)
}

fn strs(t: &Table, k: &str) -> Vec<String> {
    match t.get(k) {
        Some(Value::Array(a)) => a.iter().filter_map(|v| v.as_str().map(str::to_owned)).collect(),
        _ => Vec::new(),
    }
}

/// `[[commands]]` / `[[settings]]` blocks of a manifest's text, in order.
fn blocks(text: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut current: Option<(String, String)> = None;
    for line in text.lines() {
        let t = line.trim();
        if t == "[[commands]]" || t == "[[settings]]" {
            if let Some(b) = current.take() {
                out.push(b);
            }
            current = Some((t.trim_matches(['[', ']']).to_owned(), String::new()));
        } else if let Some((_, body)) = current.as_mut() {
            body.push_str(line);
            body.push('\n');
        }
    }
    out.extend(current);
    out
}

/// Menu → (position, menu name) of every catalog code in MainMenu.ini.
fn menu_positions() -> BTreeMap<String, (String, usize)> {
    let text = fs::read_to_string(root().join("Resources/menu/MainMenu.ini")).unwrap();
    let mut out = BTreeMap::new();
    let mut section = String::new();
    let mut name = String::new();
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            section = line.trim_matches(['[', ']']).to_owned();
            name = if section == "Top11" { "Top 11".into() } else { String::new() };
        } else if let Some(n) = line.strip_prefix("Name=") {
            name = n.to_owned();
        } else if let Some((k, v)) = line.split_once('=')
            && let Some(i) = k.strip_prefix("Icon").and_then(|i| i.parse::<usize>().ok())
            && (section.starts_with("Menu") || section == "Top11")
        {
            out.entry(v.to_owned()).or_insert((name.clone(), i));
        }
    }
    out
}

fn icon_file(code: &str) -> Option<String> {
    let dir = root().join("Resources/icons");
    let mut dirs: Vec<_> = fs::read_dir(&dir).unwrap().map(|e| e.unwrap().path()).collect();
    dirs.sort();
    dirs.into_iter().find_map(|d| {
        d.join(format!("{code}.svg"))
            .is_file()
            .then(|| format!("{}/{code}.svg", d.file_name().unwrap().to_string_lossy()))
    })
}

struct Generated {
    manifest: String,
    pages: BTreeMap<PathBuf, String>,
    readme: String,
}

fn generate() -> Generated {
    let version = env!("CARGO_PKG_VERSION");
    let mut manifest = format!(
        "# OM9 Matrix: every Matrix-style command of the OM9 add-ons in one package.\n\
         # GENERATED by addons/matrix/tests/package.rs from the menu crates; do not edit.\n\
         # tools/ci/build-addons-windows.ps1 fills @ENTRY@/@PLATFORM@.\n\
         schema_version = \"1.0.0\"\n\
         id = \"om9_matrix\"\n\
         version = \"{version}\"\n\
         name = \"OM9 Matrix\"\n\
         tagline = \"Lệnh kiểu Matrix 9 cho 11 menu: Curve, Surface, SubD, Gems …\"\n\
         maintainer = \"OpenMatrix9 contributors\"\n\
         type = \"add-on\"\n\
         license = [\"SPDX:LGPL-2.1-or-later\"]\n\
         om9_version_min = \"0.1.0\"\n\
         platforms = [\"@PLATFORM@\"]\n\
         runtime = \"native\"\n\
         entry = \"@ENTRY@\"\n\
         tags = [\"Top11\", \"Curve\", \"Surface\", \"Solid\", \"Transform\", \"SubD\", \"Builder\", \"Tools\", \"Gems\", \"Settings\", \"Cutters\"]\n\
         \n\
         # Bảng dịch giao diện (lang/vi.toml). English giữ nguyên chữ của lệnh.\n\
         [[assets]]\n\
         kind = \"lang\"\n\
         path = \"lang\"\n\
         \n\
         [[settings]]\n\
         key = \"language\"\n\
         type = \"enum\"\n\
         label = \"Ngôn ngữ / Language\"\n\
         description = \"Tên menu, lệnh, lệnh con và câu nhắc. Tên tiếng Anh luôn gõ được.\"\n\
         choices = [\"vi\", \"en\"]\n\
         choice_labels = [\"Tiếng Việt\", \"English\"]\n\
         default = \"vi\"\n\
         scope = \"addon\"\n"
    );
    let positions = menu_positions();
    let mut pages = BTreeMap::new();
    let mut index: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    let mut setting_keys = std::collections::BTreeSet::new();
    for (menu, dir) in om9_matrix::SOURCES {
        let text = fs::read_to_string(root().join(format!("addons/{dir}/addon/om9_addon.toml"))).unwrap();
        let parsed = toml::parse(&text).unwrap();
        let commands: Vec<&Table> = match parsed.get("commands") {
            Some(Value::Array(a)) => a.iter().filter_map(Value::as_table).collect(),
            _ => Vec::new(),
        };
        let settings: Vec<&Table> = match parsed.get("settings") {
            Some(Value::Array(a)) => a.iter().filter_map(Value::as_table).collect(),
            _ => Vec::new(),
        };
        let ids: Vec<String> = commands.iter().filter_map(|c| s(c, "id").map(str::to_owned)).collect();
        // Setting keys are shared by the whole package: one key, one setting.
        for t in &settings {
            let key = s(t, "key").unwrap_or_default().to_owned();
            assert!(setting_keys.insert(key.clone()), "setting key {key} is used twice (addons/{dir})");
        }
        manifest.push_str(&format!("\n# ---- {menu} (addons/{dir}) ----\n"));
        for (kind, body) in blocks(&text) {
            manifest.push_str(&format!("\n[[{kind}]]\n{}", body.trim_end_matches('\n')));
            manifest.push('\n');
            if kind == "settings" && !body.lines().any(|l| l.trim_start().starts_with("commands")) {
                let list: Vec<String> = ids.iter().map(|i| format!("\"{i}\"")).collect();
                manifest.push_str(&format!("commands = [{}]\n", list.join(", ")));
            }
        }
        for c in &commands {
            let code = s(c, "id").unwrap();
            assert_eq!(om9_matrix::category_of(code), Some(*menu), "{code} is routed to its menu");
            let label = s(c, "label").unwrap_or(code);
            let mut page = format!("# {label}\n\n");
            if let Some(sum) = s(c, "summary") {
                page.push_str(&format!("{sum}\n\n"));
            }
            page.push_str(&format!("- **Mã lệnh:** `{code}`\n"));
            match positions.get(code) {
                Some((m, i)) => page.push_str(&format!("- **Vị trí:** menu {m}, ô số {i}\n")),
                None => page.push_str("- **Vị trí:** gõ tên lệnh trên dòng lệnh hoặc tìm bằng F6\n"),
            }
            if let Some(icon) = icon_file(code) {
                page.push_str(&format!("- **Icon:** `Resources/icons/{icon}`\n"));
            }
            let mut names = vec![code.to_owned()];
            names.extend(strs(c, "aliases"));
            page.push_str(&format!(
                "- **Gọi bằng dòng lệnh:** {}\n",
                names.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", ")
            ));
            let interactive = matches!(c.get("interactive"), Some(Value::Bool(true)));
            let builder = matches!(c.get("builder"), Some(Value::Bool(true)));
            page.push_str(&format!(
                "- **Cách chạy:** {}\n",
                match (interactive, builder) {
                    (true, true) => "từng bước trên dòng lệnh, kèm bảng BUILDERS; Enter để tạo, Esc để huỷ",
                    (true, false) => "từng bước trên dòng lệnh; Enter để tạo, Esc để huỷ",
                    (false, true) => "bảng BUILDERS và tuỳ chọn dòng lệnh; Enter để tạo",
                    (false, false) => "chạy ngay với thông số đã lưu",
                }
            ));
            let steps = strs(c, "steps");
            if !steps.is_empty() {
                page.push_str("\n## Cách dùng\n\n");
                for (i, st) in steps.iter().enumerate() {
                    page.push_str(&format!("{}. {st}\n", i + 1));
                }
            }
            let options = strs(c, "options");
            let mine: Vec<&&Table> = settings
                .iter()
                .filter(|t| {
                    let cs = strs(t, "commands");
                    cs.is_empty() || cs.iter().any(|x| x == code)
                })
                .collect();
            if !options.is_empty() || !mine.is_empty() {
                page.push_str("\n## Tuỳ chọn (lệnh phụ)\n\n");
                for o in &options {
                    page.push_str(&format!("- {o}\n"));
                }
                if !mine.is_empty() {
                    page.push_str("\n| Dòng lệnh | Ý nghĩa | Mặc định | Khoảng |\n|---|---|---|---|\n");
                    for t in mine {
                        let opt = s(t, "option").map(str::to_owned).unwrap_or_else(|| s(t, "key").unwrap().to_owned());
                        let num = |k: &str| match t.get(k) {
                            Some(Value::Int(i)) => Some(i.to_string()),
                            Some(Value::Float(f)) => Some(om9_addon_abi::session::fmt(*f)),
                            Some(Value::Bool(b)) => Some(if *b { "Yes" } else { "No" }.to_owned()),
                            Some(Value::Str(x)) => Some(x.clone()),
                            _ => None,
                        };
                        let range = match (num("min"), num("max")) {
                            (Some(a), Some(b)) => format!("{a} … {b}"),
                            _ => strs(t, "choices").join(", "),
                        };
                        page.push_str(&format!(
                            "| `{opt}=` | {} | {} | {range} |\n",
                            s(t, "label").unwrap_or(""),
                            num("default").unwrap_or_default()
                        ));
                    }
                }
            }
            pages.insert(PathBuf::from(format!("commands/{menu}/{code}.md")), page);
            index.entry(menu).or_default().push(format!(
                "| `{code}` | [{label}](commands/{menu}/{code}.md) | {} |",
                positions.get(code).map_or("—".to_owned(), |(m, i)| format!("{m} #{i}"))
            ));
        }
    }
    let mut readme = String::from(
        "# OM9 Matrix\n\nGói add-on gồm các lệnh kiểu Matrix 9 cho OM9. Sau khi cài và bật gói, lệnh\n\
         gọi được từ icon trên menu, từ dòng lệnh (tên lệnh hoặc tên gõ tắt) và từ F6. Khi gói\n\
         đang bật, lệnh của add-on được dùng thay cho lệnh cùng tên có sẵn trong OM9; tắt gói\n\
         để quay lại lệnh có sẵn.\n\nMỗi lệnh có một trang trong `commands/<Menu>/`.\n",
    );
    let total: usize = index.values().map(Vec::len).sum();
    readme.push_str(&format!("\nTổng cộng: {total} lệnh.\n"));
    for (menu, rows) in &index {
        readme.push_str(&format!(
            "\n## {menu} ({} lệnh)\n\n| Mã lệnh | Lệnh | Vị trí menu |\n|---|---|---|\n{}\n",
            rows.len(),
            rows.join("\n")
        ));
    }
    Generated {
        manifest,
        pages,
        readme,
    }
}

/// (code, aliases) of every command of a manifest.
fn cmds_of(manifest: &str) -> Vec<(String, Vec<String>)> {
    let parsed = toml::parse(manifest).unwrap();
    let Some(Value::Array(cmds)) = parsed.get("commands") else { return Vec::new() };
    cmds.iter()
        .filter_map(Value::as_table)
        .map(|t| (s(t, "id").unwrap().to_owned(), strs(t, "aliases")))
        .collect()
}

#[test]
fn package_files_match_the_menu_crates() {
    let g = generate();
    let addon = Path::new(env!("CARGO_MANIFEST_DIR")).join("addon");
    if std::env::var_os("OM9_UPDATE_PACKAGE").is_some() {
        let _ = fs::remove_dir_all(addon.join("commands"));
        fs::create_dir_all(&addon).unwrap();
        fs::write(addon.join("om9_addon.toml"), &g.manifest).unwrap();
        fs::write(addon.join("README.md"), &g.readme).unwrap();
        for (p, text) in &g.pages {
            let f = addon.join(p);
            fs::create_dir_all(f.parent().unwrap()).unwrap();
            fs::write(f, text).unwrap();
        }
        // The command icons a manifest references travel with the package.
        fs::create_dir_all(addon.join("icons")).unwrap();
        for e in fs::read_dir(root().join("addons/gem_on_curve/addon/icons")).unwrap() {
            let e = e.unwrap().path();
            fs::copy(&e, addon.join("icons").join(e.file_name().unwrap())).unwrap();
        }
        return;
    }
    let read = |p: &Path| fs::read_to_string(p).unwrap_or_default();
    assert_eq!(read(&addon.join("om9_addon.toml")), g.manifest, "OM9_UPDATE_PACKAGE=1 to regenerate");
    assert_eq!(read(&addon.join("README.md")), g.readme);
    for (p, text) in &g.pages {
        assert_eq!(&read(&addon.join(p)), text, "{}", p.display());
    }
    // A typed name calls one command only.
    let mut names = std::collections::BTreeMap::<String, String>::new();
    for c in cmds_of(&g.manifest) {
        for n in std::iter::once(c.0.clone()).chain(c.1.iter().cloned()) {
            if let Some(other) = names.insert(n.to_ascii_lowercase(), c.0.clone())
                && other != c.0
            {
                panic!("{n} names both {other} and {}", c.0);
            }
        }
    }
    // Every package command is routed, and every routed command is in the package.
    let parsed = toml::parse(&g.manifest).unwrap();
    let Some(Value::Array(cmds)) = parsed.get("commands") else { panic!() };
    let ids: Vec<&str> = cmds.iter().filter_map(|c| c.as_table().and_then(|t| s(t, "id"))).collect();
    let mut all: Vec<&str> = om9_matrix::ALL.to_vec();
    all.sort_unstable();
    let mut sorted = ids.clone();
    sorted.sort_unstable();
    assert_eq!(sorted, all);
}

/// `lang/vi.toml` parses, names every command and menu of the package, and the language
/// setting is an add-on setting (never a command option).
#[test]
fn vietnamese_table_covers_the_package() {
    use om9_addons::i18n::{Lang, Tr};
    let addon = Path::new(env!("CARGO_MANIFEST_DIR")).join("addon");
    let text = fs::read_to_string(addon.join("lang/vi.toml")).unwrap();
    let tr = Tr::parse(&text, Lang::Vi).unwrap_or_else(|e| panic!("lang/vi.toml: {e:?}"));
    let parsed = toml::parse(&generate().manifest).unwrap();
    let Some(Value::Array(cmds)) = parsed.get("commands") else {
        panic!()
    };
    let missing: Vec<&str> = cmds
        .iter()
        .filter_map(|c| c.as_table().and_then(|t| s(t, "id")))
        .filter(|code| tr.command(code, "\u{0}") == "\u{0}")
        .collect();
    assert!(missing.is_empty(), "no Vietnamese name: {missing:?}");
    for (_, (menu, _)) in menu_positions() {
        assert_ne!(tr.menu(&menu), menu, "menu {menu}");
    }
    let Some(Value::Array(settings)) = parsed.get("settings") else {
        panic!()
    };
    let lang = settings
        .iter()
        .filter_map(Value::as_table)
        .find(|t| s(t, "key") == Some("language"))
        .expect("language setting");
    assert_eq!(s(lang, "scope"), Some("addon"));
    assert_eq!(s(lang, "default"), Some("vi"));
}

/// Every prompt and message of the Curve commands reworked to the Matrix 9 sub-options has a
/// Vietnamese text (placeholders filled with sample values).
#[test]
fn curve_prompts_have_vietnamese() {
    use om9_addons::i18n::{Lang, Tr};
    let addon = Path::new(env!("CARGO_MANIFEST_DIR")).join("addon");
    let tr = Tr::parse(&fs::read_to_string(addon.join("lang/vi.toml")).unwrap(), Lang::Vi).unwrap();
    let single = ["Width", "Height", "Radius", "Diameter", "Circumference", "Area", "Ellipse"];
    let mut missing = Vec::new();
    let files = [
        "curves/src/line",
        "curves/src/polyline",
        "curves/src/interp",
        "curves/src/rect",
        "curves/src/circle",
        "curves/src/ellipse",
        "curves/src/arc",
        "curves/src/polygon",
        "curves/src/spiral",
        "curve_tools/src/fillet",
        "curve_tools/src/blend",
        "curve_tools/src/offset",
        "curve_tools/src/extend",
        "curve_tools/src/edit",
        "curve_tools/src/regions",
        "curve_tools/src/sections",
        "curve_tools/src/objects",
        "curve_tools/src/lib",
        "geom/src/cmd",
    ];
    for f in files {
        let src = fs::read_to_string(root().join(format!("addons/{f}.rs"))).unwrap();
        let code: String = src
            .split("#[cfg(test)]")
            .next()
            .unwrap()
            .lines()
            .filter(|l| !l.trim_start().starts_with("//"))
            .collect::<Vec<_>>()
            .join("\n");
        let mut rest = code.as_str();
        while let Some(i) = rest.find('"') {
            let after = &rest[i + 1..];
            let mut end = 0;
            let bytes = after.as_bytes();
            while end < bytes.len() && bytes[end] != b'"' {
                end += if bytes[end] == b'\\' { 2 } else { 1 };
            }
            let lit = &after[..end.min(after.len())];
            rest = &after[(end + 1).min(after.len())..];
            let starts_upper = lit.chars().next().is_some_and(|c| c.is_ascii_uppercase());
            if !(starts_upper && (lit.contains(' ') || single.contains(&lit))) {
                continue;
            }
            let sample = lit
                .replace("{text}", "x")
                .replace("{name}", "Foo")
                .replace("{n}", "1")
                .replace("{}", "1");
            if tr.text(&sample) == sample {
                missing.push(format!("{f}: {lit}"));
            }
        }
    }
    assert!(missing.is_empty(), "no Vietnamese text: {missing:#?}");
}
