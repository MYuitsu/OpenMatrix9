//! Matrix Surface menu binding catalog (`OM9-L2-03-17`).
//!
//! One row per documented Surface Tools command. Every row names the authored icon, a
//! unique command id and the verified owner candidate. No surface command has an
//! interactive session yet, so every row is a visible disabled placeholder rather than a
//! fake success. History rows share their base command icon but keep a distinct id.

/// Why a menu row is not enabled.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BindingState {
    Implemented,
    SessionMissing,
    OwnerMissing,
}

/// One Surface menu row.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SurfaceMenuBinding {
    pub l3_id: &'static str,
    pub label: &'static str,
    pub source_command: &'static str,
    pub icon: &'static str,
    pub feature: &'static str,
    pub owner: &'static str,
    pub state: BindingState,
    pub disabled_reason: &'static str,
}

impl SurfaceMenuBinding {
    pub fn enabled(&self) -> bool {
        matches!(self.state, BindingState::Implemented)
    }
}

