/// Resolve a row by its documented L3 id.
pub fn by_l3(l3_id: &str) -> Option<&'static CurveMenuBinding> {
    BINDINGS.iter().find(|binding| binding.l3_id == l3_id)
}

/// Resolve a row by its stable command feature id.
pub fn by_feature(feature: &str) -> Option<&'static CurveMenuBinding> {
    BINDINGS.iter().find(|binding| binding.feature == feature)
}

/// Resolve a row by the authored icon name used by the menu palette.
pub fn by_icon(icon: &str) -> Option<&'static CurveMenuBinding> {
    BINDINGS.iter().find(|binding| binding.icon == icon)
}

/// Whether the row is enabled by its verified interactive session.
pub fn enabled(feature: &str) -> bool {
    by_feature(feature).is_some_and(CurveMenuBinding::enabled)
}

/// The user-visible reason a disabled row stays disabled.
pub fn disabled_reason(feature: &str) -> Option<&'static str> {
    by_feature(feature).and_then(|binding| (!binding.enabled()).then_some(binding.disabled_reason))
}
