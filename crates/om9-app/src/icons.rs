struct Icon {
    name: &'static str,
    command_key: &'static str,
    feature: &'static str,
    svg: &'static [u8],
}
macro_rules! icon {
    ($name:literal, $key:literal, $feature:literal, $source:literal) => {
        Icon {
            name: $name,
            command_key: $key,
            feature: $feature,
            svg: include_bytes!(concat!("../../../Resources/icons/", $source)),
        }
    };
}
