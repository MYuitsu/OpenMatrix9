/// Menu icons for one top menu or category, in the reference order.
pub fn category(name: &str) -> Option<&'static [&'static str]> {
    match name {
        "File" => Some(FILE),
        "View" => Some(VIEW),
        "Utilities" => Some(UTILITIES),
        "Measure" => Some(MEASURE),
        "Custom" => Some(&[]),
        "Curve" => Some(CURVE),
        "Surface" => Some(SURFACE),
        "Solid" => Some(SOLID),
        "Transform" => Some(TRANSFORM),
        "SubD" => Some(SUBD),
        "Art" => Some(ART),
        "Builder" => Some(BUILDER),
        "Tools" => Some(TOOLS),
        "Gems" => Some(GEMS),
        "Setting" => Some(SETTING),
        "Cutters" => Some(CUTTERS),
        "Render" => Some(RENDER),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_menu_has_the_full_reference_icon_list() {
        for (name, expected) in [
            ("Curve", 58),
            ("Surface", 40),
            ("Solid", 30),
            ("Transform", 40),
            ("SubD", 58),
            ("Art", 7),
            ("Builder", 16),
            ("Tools", 31),
            ("Gems", 35),
            ("Setting", 12),
            ("Cutters", 11),
            ("Render", 23),
            ("File", 13),
            ("View", 15),
            ("Utilities", 22),
            ("Measure", 17),
            ("Custom", 0),
        ] {
            let icons = category(name).unwrap_or_else(|| panic!("{name} menu"));
            assert_eq!(icons.len(), expected, "{name} icon count");
            for icon in icons {
                assert!(
                    crate::icons::icon_name(icon).is_some(),
                    "{name}: missing authored icon {icon}"
                );
            }
        }
    }

    #[test]
    fn most_reference_icons_map_to_a_feature() {
        let mapped = [
            "Curve",
            "Surface",
            "Solid",
            "Transform",
            "SubD",
            "Art",
            "Builder",
            "Tools",
            "Gems",
            "Setting",
            "Cutters",
            "Render",
            "File",
            "View",
            "Utilities",
            "Measure",
        ]
        .iter()
        .flat_map(|name| category(name).unwrap_or(&[]).iter())
        .filter(|name| crate::icons::feature_for(name).is_some())
        .count();
        assert!(mapped >= 350, "only {mapped} menu icons map to features");
    }
}
