"""Generate tools/matrix_m04_anchors.py from the tree-derived M04 sheet map.

The M04 anchor rows keep their hand-authored Rhino 5 chapters, Matrix9 sources and
focus line from tools/matrix_ref_crosswalk.py, and gain one anchor per authored
sheet that ships under the L3 (or its parent L2). That way every sheet shipped
with the milestone is referenced without hand-maintaining the list.

Usage: python tools/gen_m04_anchors.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import matrix_ref_crosswalk as cw  # noqa: E402

MAP = ROOT / "build" / "m04-sheet-map.json"
OUT = ROOT / "tools" / "matrix_m04_anchors.py"


def sheet_anchor(sheet):
    return "mx-sheet-" + re.sub(r"[^a-z0-9]+", "-", sheet.lower()).strip("-")


def main():
    sheet_map = json.loads(MAP.read_text(encoding="utf-8"))
    existing = getattr(cw, "M04_ANCHORS", {})
    lines = ['"""M04 L3 anchor rows (generated).',
             "",
             "Generated by tools/gen_m04_anchors.py: the Rhino 5 chapters, Matrix9 sources and focus",
             "line are taken from the authored crosswalk, and one anchor is added per reference sheet",
             "that ships under the L3 (or its parent L2). Edit the generator or the crosswalk, not",
             "this file.",
             '"""',
             "",
             "M04_ANCHORS = {"]
    rows = 0
    sheet_refs = 0
    missing_row = []
    for l3_id in sorted(sheet_map):
        if l3_id not in cw.L3_ANCHORS:
            missing_row.append(l3_id)
            continue
        row = cw.L3_ANCHORS[l3_id]
        mx = dict(row.get("mx", {}))
        for sheet in sheet_map[l3_id]["sheets"]:
            anchor = sheet_anchor(sheet)
            mx.setdefault(anchor, f"authored sheet in this L3: {sheet}")
        sheet_refs += sum(1 for k in mx if k.startswith("mx-sheet-"))
        lines.append(f"    {l3_id!r}: dict(")
        lines.append(f"        rcore={row.get('rcore', [])!r},")
        lines.append(f"        mx={mx!r},")
        lines.append(f"        focus={row['focus']!r}),")
        rows += 1
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({
        "rows": rows,
        "sheet_anchors": sheet_refs,
        "l3_without_crosswalk_row": missing_row,
        "previous_hand_rows": len(existing),
    }, indent=1))


if __name__ == "__main__":
    main()
