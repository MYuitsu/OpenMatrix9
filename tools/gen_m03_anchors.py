def main():
    rows = json.loads(TABLE.read_text(encoding="utf-8"))
    lines = ['"""M03 L3 anchor rows (generated).',
             "",
             "Generated by tools/gen_m03_anchors.py from the authored sheet crosswalk; each row",
             "carries the Rhino 5 chapters, the Matrix9 sources and the exact manual sheet for the",
             "M03 menu command. Edit the generator, not this file.",
             '"""',
             "",
             "M03_ANCHORS = {"]
    count = 0
    for row in rows:
        l3 = row["l3"]
        l2 = row["l2"]
        rcore, mx = L2_DEFAULTS[l2]
        if l3 in L3_OVERRIDES:
            override_rcore, override_mx = L3_OVERRIDES[l3]
            rcore = override_rcore
            if override_mx:
                mx = override_mx
        focus = FOCUS_BY_L2[l2]
        mx_map = {source: "M03 " + l2 + " reference source" for source in mx}
        sheets = row.get("sheets") or ([row["sheet"]] if row.get("sheet") else [])
        for sheet in sheets:
            anchor = "mx-sheet-" + re.sub(r"[^a-z0-9]+", "-", sheet.lower()).strip("-")
            mx_map[anchor] = f"authored sheet in this L3: {sheet}"
        lines.append(f"    {l3!r}: dict(")
        lines.append(f"        rcore={rcore!r},")
        lines.append(f"        mx={mx_map!r},")
        lines.append(f"        focus={focus!r}),")
        count += 1
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps({"rows": count}))


if __name__ == "__main__":
    main()
